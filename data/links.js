function queryFor(work, edition) {
  return edition.isbn || [edition.title, work.author].filter(Boolean).join(" ");
}

function standardOffers(work, edition, lang) {
  const query = encodeURIComponent(queryFor(work, edition));
  const offers = lang === "fr"
    ? [
        {
          id: "amazon",
          merchant: "Amazon",
          url: `https://www.amazon.fr/s?k=${query}&tag=${encodeURIComponent(AMAZON_FR_TAG)}`,
          affiliate: true
        },
        { id: "fnac", merchant: "Fnac", url: `https://www.fnac.com/SearchResult/ResultList.aspx?Search=${query}` },
        { id: "kobo", merchant: "Kobo", url: `https://www.kobo.com/fr/fr/search?query=${query}` }
      ]
    : [
        { id: "amazon", merchant: "Amazon", url: `https://www.amazon.com/s?k=${query}` },
        { id: "kobo", merchant: "Kobo", url: `https://www.kobo.com/us/en/search?query=${query}` }
      ];

  return offers.map((offer) => {
    const affiliateUrl = AFFILIATE_OVERRIDES[`${work.id}:${lang}:${offer.id}`] || "";
    return {
      ...offer,
      url: affiliateUrl || offer.url,
      affiliate: Boolean(affiliateUrl) || Boolean(offer.affiliate)
    };
  });
}

function blogReviewFallback(work, edition, lang) {
  const query = lang === "fr"
    ? `"${edition.title}" "${work.author}" critique blog littéraire`
    : `"${edition.title}" "${work.author}" book review blog`;

  return {
    lang,
    search: true,
    source: lang === "fr" ? "Recherche ciblée" : "Targeted search",
    kind: lang === "fr" ? "Blogs littéraires" : "Literary blogs",
    title: lang === "fr"
      ? `Rechercher des chroniques de ${edition.title}`
      : `Search for blog reviews of ${edition.title}`,
    url: `https://www.google.com/search?q=${encodeURIComponent(query)}`
  };
}

export function linksFor(work, edition, lang) {
  const curated = (reviewsByWork[work.id] || []).filter((review) => !review.lang || review.lang === lang);
  return {
    offers: standardOffers(work, edition, lang),
    reviews: curated.length ? curated : [blogReviewFallback(work, edition, lang)]
  };
}
