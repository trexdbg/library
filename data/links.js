function queryFor(work, edition) {
  return edition.isbn || [edition.title, work.author].filter(Boolean).join(" ");
}

function standardOffers(work, edition, lang) {
  const query = encodeURIComponent(queryFor(work, edition));
  const offers = lang === "fr"
    ? [
        { id: "amazon", merchant: "Amazon", url: `https://www.amazon.fr/s?k=${query}` },
        { id: "fnac", merchant: "Fnac", url: `https://www.fnac.com/SearchResult/ResultList.aspx?Search=${query}` },
        { id: "kobo", merchant: "Kobo", url: `https://www.kobo.com/fr/fr/search?query=${query}` }
      ]
    : [
        { id: "amazon", merchant: "Amazon", url: `https://www.amazon.com/s?k=${query}` },
        { id: "kobo", merchant: "Kobo", url: `https://www.kobo.com/us/en/search?query=${query}` }
      ];

  return offers.map((offer) => {
    const affiliateUrl = AFFILIATE_OVERRIDES[`${work.id}:${lang}:${offer.id}`] || "";
    return {
      ...offer,
      url: affiliateUrl || offer.url,
      affiliate: Boolean(affiliateUrl)
    };
  });
}

export function linksFor(work, edition, lang) {
  return {
    offers: standardOffers(work, edition, lang),
    reviews: reviewsByWork[work.id] || []
  };
}
